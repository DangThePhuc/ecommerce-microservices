// Order Service - Order Management Bounded Context. DB: PostgreSQL (Order DB): orders, order_details (+ outbox_events).
// Nhan gRPC tu Gateway, goi gRPC sang Product Service, ghi Order + OrderDetail + OutboxEvent trong 1 transaction,
// publisher nen gui OrderCreated len Kafka (Transactional Outbox).
const path = require('path');
const http = require('http');
const { randomUUID } = require('crypto');
const { Pool } = require('pg');
const { Kafka } = require('kafkajs');
const grpc = require('@grpc/grpc-js');
const protoLoader = require('@grpc/proto-loader');
const { calculateDiscount } = require('./discount');

const PORT = Number(process.env.PORT || 3004);
const GRPC_PORT = Number(process.env.GRPC_PORT || 50054);
const TOPIC = process.env.ORDER_CREATED_TOPIC || 'order-created';
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

const kafka = new Kafka({ clientId: 'order-service', brokers: [process.env.KAFKA_BROKER], retry: { retries: 10 } });
const producer = kafka.producer();
let kafkaReady = false;

const opts = { keepCase: true, longs: Number, defaults: true };
const load = (f) => grpc.loadPackageDefinition(protoLoader.loadSync(path.join(__dirname, '../proto', f), opts));
const orderPkg = load('order.proto').order;
const productPkg = load('product.proto').product;
const productClient = new productPkg.ProductService(process.env.PRODUCT_GRPC_URL, grpc.credentials.createInsecure());
const callProduct = (method, req) =>
  new Promise((resolve, reject) =>
    productClient[method](req, { deadline: Date.now() + 5000 }, (e, r) => (e ? reject(e) : resolve(r))));

class GrpcError extends Error {
  constructor(code, message) { super(message); this.grpcCode = code; }
}
const fromDownstream = (e) => new GrpcError(typeof e.code === 'number' ? e.code : grpc.status.UNAVAILABLE, e.details || e.message);
const wrap = (fn) => async (call, cb) => {
  try { cb(null, await fn(call)); } catch (e) {
    if (e instanceof GrpcError) return cb({ code: e.grpcCode, details: e.message });
    console.error('[order]', e);
    cb({ code: grpc.status.INTERNAL, details: 'Internal server error' });
  }
};
const caller = (call) => ({
  uid: Number((call.metadata.get('x-user-id') || [])[0]) || 0,
  role: (call.metadata.get('x-user-role') || [])[0] || '',
});

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function retry(fn, name, tries = 30) {
  for (let i = 1; i <= tries; i++) {
    try { return await fn(); } catch (e) {
      console.error(`[order] ${name} chua san sang (${i}/${tries}): ${e.message}`);
      await sleep(2000);
    }
  }
  throw new Error(`${name} failed`);
}

async function initDb() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS orders (
      oid INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
      uid INT NOT NULL,
      discount DECIMAL(10,2) NOT NULL DEFAULT 0
    )`);
  await pool.query(`
    CREATE TABLE IF NOT EXISTS order_details (
      oid INT NOT NULL REFERENCES orders(oid) ON DELETE CASCADE,
      pid INT NOT NULL,
      qty INT NOT NULL CHECK (qty > 0),
      unit_price DECIMAL(10,2) NOT NULL,
      PRIMARY KEY (oid, pid)
    )`);
  await pool.query(`
    CREATE TABLE IF NOT EXISTS outbox_events (
      id BIGSERIAL PRIMARY KEY,
      aggregate_id INT NOT NULL,
      event_type VARCHAR(50) NOT NULL,
      payload JSONB NOT NULL,
      status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      published_at TIMESTAMPTZ
    )`);
}

async function initKafka() {
  const admin = kafka.admin();
  await admin.connect();
  await admin.createTopics({ topics: [{ topic: TOPIC, numPartitions: 1, replicationFactor: 1 }] });
  await admin.disconnect();
  await producer.connect();
  kafkaReady = true;
  console.log(`[order] Kafka producer san sang, topic=${TOPIC}`);
}

// ----- Outbox publisher (BPM buoc 9, bat dong bo) -----
let publishing = false;
async function publishPending() {
  if (publishing || !kafkaReady) return;
  publishing = true;
  const c = await pool.connect();
  try {
    await c.query('BEGIN');
    const { rows } = await c.query(
      `SELECT id, aggregate_id, payload FROM outbox_events
       WHERE status='PENDING' ORDER BY id LIMIT 20 FOR UPDATE SKIP LOCKED`);
    if (rows.length) {
      await producer.send({
        topic: TOPIC,
        messages: rows.map((r) => ({ key: String(r.aggregate_id), value: JSON.stringify(r.payload) })),
      });
      await c.query(`UPDATE outbox_events SET status='PUBLISHED', published_at=now() WHERE id = ANY($1)`,
        [rows.map((r) => r.id)]);
      console.log(`[order] da publish ${rows.length} event OrderCreated len Kafka`);
    }
    await c.query('COMMIT');
  } catch (e) {
    await c.query('ROLLBACK').catch(() => {});
    console.error('[order] publish outbox loi (se thu lai):', e.message);
  } finally {
    c.release();
    publishing = false;
  }
}

const round2 = (n) => Math.round(n * 100) / 100;

function normalizeItems(items) {
  if (!items || !items.length) return null;
  const map = new Map();
  for (const it of items) {
    if (!Number.isInteger(it.pid) || !Number.isInteger(it.qty) || it.qty <= 0 || it.pid <= 0) return null;
    map.set(it.pid, (map.get(it.pid) || 0) + it.qty);
  }
  return [...map].map(([pid, qty]) => ({ pid, qty }));
}

const handlers = {
  CreateOrder: wrap(async (call) => {
    const { uid, score } = call.request;
    const items = normalizeItems(call.request.items);
    if (!uid) throw new GrpcError(grpc.status.UNAUTHENTICATED, 'Unauthorized');
    if (!items) throw new GrpcError(grpc.status.INVALID_ARGUMENT, 'items khong hop le (pid, qty phai la so nguyen duong)');

    // BPM buoc 5: tinh muc giam gia theo score
    const discount = calculateDiscount(score);

    // BPM buoc 6: kiem tra gia + so luong san pham (gRPC)
    let info;
    try { info = (await callProduct('CheckProducts', { pids: items.map((i) => i.pid) })).items; }
    catch (e) { throw fromDownstream(e); }
    const price = new Map(info.map((p) => [p.pid, p]));
    for (const it of items) {
      if (it.qty > price.get(it.pid).quantity) {
        throw new GrpcError(grpc.status.FAILED_PRECONDITION, `Khong du ton kho cho san pham ${it.pid}`);
      }
    }

    // BPM buoc 7: cap nhat ton kho (gRPC)
    try { await callProduct('UpdateInventory', { items }); }
    catch (e) { throw fromDownstream(e); }

    const lines = items.map((i) => ({ pid: i.pid, qty: i.qty, unit_price: price.get(i.pid).price }));
    const subtotal = round2(lines.reduce((s, l) => s + l.unit_price * l.qty, 0));
    const total = round2((subtotal * (100 - discount)) / 100);

    // BPM buoc 8: Order + OrderDetail + OutboxEvent trong cung 1 transaction
    const c = await pool.connect();
    try {
      await c.query('BEGIN');
      const o = await c.query('INSERT INTO orders(uid, discount) VALUES ($1,$2) RETURNING oid', [uid, discount]);
      const oid = o.rows[0].oid;
      for (const l of lines) {
        await c.query('INSERT INTO order_details(oid, pid, qty, unit_price) VALUES ($1,$2,$3,$4)',
          [oid, l.pid, l.qty, l.unit_price]);
      }
      const event = {
        eventId: randomUUID(), eventType: 'OrderCreated', oid, uid, discount,
        total_amount: total, items: lines, createdAt: new Date().toISOString(),
      };
      await c.query('INSERT INTO outbox_events(aggregate_id, event_type, payload) VALUES ($1,$2,$3)',
        [oid, 'OrderCreated', JSON.stringify(event)]);
      await c.query('COMMIT');
      publishPending();
      return { oid, uid, discount, subtotal, total_amount: total, items: lines, shipment_status: 'PENDING' };
    } catch (e) {
      await c.query('ROLLBACK').catch(() => {});
      await callProduct('RestoreInventory', { items })
        .catch((er) => console.error('[order] hoan kho loi:', er.message));
      throw e;
    } finally {
      c.release();
    }
  }),

  ListOrders: wrap(async (call) => {
    const c = caller(call);
    if (!c.uid) throw new GrpcError(grpc.status.UNAUTHENTICATED, 'Unauthorized');
    const sql = `SELECT o.oid, o.uid, o.discount, COALESCE(SUM(d.qty * d.unit_price),0) AS subtotal
                 FROM orders o LEFT JOIN order_details d ON d.oid = o.oid
                 ${c.role === 'ADMIN' ? '' : 'WHERE o.uid = $1'} GROUP BY o.oid ORDER BY o.oid DESC`;
    const r = await pool.query(sql, c.role === 'ADMIN' ? [] : [c.uid]);
    return {
      items: r.rows.map((o) => {
        const discount = Number(o.discount), subtotal = Number(o.subtotal);
        return { oid: o.oid, uid: o.uid, discount, subtotal, total_amount: round2((subtotal * (100 - discount)) / 100) };
      }),
    };
  }),

  GetOrder: wrap(async (call) => {
    const c = caller(call);
    if (!c.uid) throw new GrpcError(grpc.status.UNAUTHENTICATED, 'Unauthorized');
    const o = await pool.query('SELECT oid, uid, discount FROM orders WHERE oid=$1', [call.request.oid]);
    if (!o.rows[0]) throw new GrpcError(grpc.status.NOT_FOUND, 'Order not found');
    const order = o.rows[0];
    if (c.role !== 'ADMIN' && order.uid !== c.uid) throw new GrpcError(grpc.status.PERMISSION_DENIED, 'Forbidden');
    const d = await pool.query('SELECT pid, qty, unit_price FROM order_details WHERE oid=$1 ORDER BY pid', [order.oid]);
    const items = d.rows.map((i) => ({ pid: i.pid, qty: i.qty, unit_price: Number(i.unit_price) }));
    const discount = Number(order.discount);
    const subtotal = round2(items.reduce((s, i) => s + i.unit_price * i.qty, 0));
    return { oid: order.oid, uid: order.uid, discount, subtotal, total_amount: round2((subtotal * (100 - discount)) / 100), items, shipment_status: '' };
  }),
};

(async () => {
  await retry(initDb, 'postgres');
  await retry(initKafka, 'kafka');
  setInterval(publishPending, 3000);
  const server = new grpc.Server();
  server.addService(orderPkg.OrderService.service, handlers);
  server.bindAsync(`0.0.0.0:${GRPC_PORT}`, grpc.ServerCredentials.createInsecure(), (err) => {
    if (err) throw err;
    console.log(`[order] gRPC listening on ${GRPC_PORT}`);
  });
  http.createServer(async (req, res) => {
    try {
      await pool.query('SELECT 1');
      if (!kafkaReady) throw new Error('kafka');
      res.writeHead(200, { 'Content-Type': 'application/json' }); res.end('{"status":"UP","service":"order-service"}');
    } catch { res.writeHead(503); res.end('{"status":"DOWN"}'); }
  }).listen(PORT, () => console.log(`[order] health on ${PORT}`));
})();
