const crypto = require('crypto');
const { Pool, types } = require('pg');
const { grpc, loadProto, err, wrap, startServer, retry, RpcError } = require('./grpc');
const { discountForScore, calcTotals } = require('./discount');
const kafka = require('./kafka');
const outbox = require('./outbox');

const PORT = process.env.GRPC_PORT || 50054;
types.setTypeParser(1700, parseFloat); // NUMERIC -> number

const pool = new Pool({ connectionString: process.env.DATABASE_URL });

// ───────────── gRPC clients tới Customer Service và Product Service ─────────────
const customerProto = loadProto('customer.proto');
const productProto = loadProto('product.proto');
const customerClient = new customerProto.customer.CustomerService(
  process.env.CUSTOMER_GRPC_URL || 'customer-service:50052', grpc.credentials.createInsecure());
const productClient = new productProto.product.ProductService(
  process.env.PRODUCT_GRPC_URL || 'product-service:50053', grpc.credentials.createInsecure());

function rpc(client, method, req) {
  return new Promise((resolve, reject) => {
    client[method](req, { deadline: Date.now() + 5000 }, (e, res) => {
      if (!e) return resolve(res);
      // Giữ nguyên mã lỗi của service phía dưới (404, 409, ...)
      reject(new RpcError(e.code ?? grpc.status.UNAVAILABLE, e.details || e.message));
    });
  });
}

async function migrate() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS orders (
      oid          INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
      uid          INT NOT NULL,
      discount     DECIMAL(10,2) NOT NULL DEFAULT 0,
      total_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
      created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE TABLE IF NOT EXISTS order_details (
      oid        INT NOT NULL REFERENCES orders(oid) ON DELETE CASCADE,
      pid        INT NOT NULL,
      qty        INT NOT NULL CHECK (qty > 0),
      unit_price DECIMAL(10,2) NOT NULL,
      PRIMARY KEY (oid, pid)
    );
    CREATE TABLE IF NOT EXISTS outbox_events (
      id           BIGSERIAL PRIMARY KEY,
      event_id     UUID NOT NULL UNIQUE,
      aggregate_id INT  NOT NULL,
      event_type   VARCHAR(50) NOT NULL,
      payload      JSONB NOT NULL,
      status       VARCHAR(20) NOT NULL DEFAULT 'PENDING',
      created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      published_at TIMESTAMPTZ
    );
    CREATE INDEX IF NOT EXISTS idx_outbox_pending ON outbox_events (status, id);
    CREATE INDEX IF NOT EXISTS idx_orders_uid ON orders (uid);
  `);
}

const toDto = (o, items) => ({
  oid: o.oid,
  uid: o.uid,
  discount: o.discount,
  total_amount: o.total_amount,
  created_at: new Date(o.created_at).toISOString(),
  items: items.map((i) => ({ pid: i.pid, qty: i.qty, unit_price: i.unit_price })),
});

function normalizeItems(items) {
  if (!Array.isArray(items) || !items.length) throw err.invalid('items must be a non-empty array');
  const map = new Map();
  for (const it of items) {
    if (!it || !Number.isInteger(it.pid) || it.pid <= 0 || !Number.isInteger(it.qty) || it.qty <= 0) {
      throw err.invalid('each item needs positive integer pid and qty');
    }
    map.set(it.pid, (map.get(it.pid) || 0) + it.qty);
  }
  return [...map].map(([pid, qty]) => ({ pid, qty }));
}

async function createOrder({ uid, items }) {
  if (!Number.isInteger(uid) || uid <= 0) throw err.unauthenticated('invalid user');
  const list = normalizeItems(items);

  // (3-4) Lấy thông tin Customer + score từ Customer Service -> (5) tính discount
  const membership = await rpc(customerClient, 'GetMembership', { uid });
  const discount = discountForScore(membership.score);

  // (6) Kiểm tra sản phẩm + tồn kho; (7) trừ tồn kho (gRPC tới Product Service)
  await rpc(productClient, 'CheckStock', { items: list });
  const reserved = await rpc(productClient, 'ReserveStock', { items: list });
  const lines = reserved.items;
  const { total } = calcTotals(lines, discount);

  // (8) Transaction: Order + OrderDetail + OutboxEvent
  const client = await pool.connect();
  let order;
  try {
    await client.query('BEGIN');
    const o = await client.query(
      'INSERT INTO orders (uid, discount, total_amount) VALUES ($1, $2, $3) RETURNING oid, uid, discount, total_amount, created_at',
      [uid, discount, total]
    );
    order = o.rows[0];
    for (const l of lines) {
      await client.query('INSERT INTO order_details (oid, pid, qty, unit_price) VALUES ($1, $2, $3, $4)', [order.oid, l.pid, l.qty, l.unit_price]);
    }
    const dto = toDto(order, lines);
    const event = {
      eventId: crypto.randomUUID(),
      eventType: 'OrderCreated',
      occurredAt: dto.created_at,
      oid: dto.oid,
      uid: dto.uid,
      discount: dto.discount,
      totalAmount: dto.total_amount,
      items: dto.items,
    };
    await client.query(
      'INSERT INTO outbox_events (event_id, aggregate_id, event_type, payload) VALUES ($1, $2, $3, $4)',
      [event.eventId, dto.oid, event.eventType, JSON.stringify(event)]
    );
    await client.query('COMMIT');
  } catch (e) {
    await client.query('ROLLBACK').catch(() => {});
    // Bù trừ: hoàn lại tồn kho đã trừ để dữ liệu không bị lệch
    await rpc(productClient, 'ReleaseStock', { items: list }).catch((re) => console.error('ReleaseStock failed:', re.message));
    throw e;
  } finally {
    client.release();
  }

  // (9) Phát sự kiện (bất đồng bộ) - nếu Kafka lỗi, event vẫn PENDING trong outbox
  outbox.kick(pool);
  return toDto(order, lines);
}

async function loadItems(oids) {
  const { rows } = await pool.query('SELECT oid, pid, qty, unit_price FROM order_details WHERE oid = ANY($1) ORDER BY pid', [oids]);
  return rows;
}

const impl = {
  CreateOrder: wrap('CreateOrder', createOrder),

  GetOrder: wrap('GetOrder', async ({ oid, uid, role }) => {
    const { rows } = await pool.query('SELECT * FROM orders WHERE oid = $1', [oid]);
    if (!rows[0]) throw err.notFound('Order not found');
    if (role !== 'admin' && rows[0].uid !== uid) throw err.forbidden('You cannot access this order');
    return toDto(rows[0], await loadItems([oid]));
  }),

  ListOrders: wrap('ListOrders', async ({ uid, role }) => {
    const { rows } = role === 'admin'
      ? await pool.query('SELECT * FROM orders ORDER BY oid DESC')
      : await pool.query('SELECT * FROM orders WHERE uid = $1 ORDER BY oid DESC', [uid]);
    const details = rows.length ? await loadItems(rows.map((r) => r.oid)) : [];
    return { items: rows.map((o) => toDto(o, details.filter((d) => d.oid === o.oid))) };
  }),

  Health: wrap('Health', async () => {
    await pool.query('SELECT 1');
    return { status: 'UP', kafka: kafka.isConnected() ? 'UP' : 'DOWN' };
  }),
};

(async () => {
  await retry('order-db', migrate);
  await kafka.init();
  const proto = loadProto('order.proto');
  await startServer(proto.order.OrderService.service, impl, PORT);
  outbox.start(pool, parseInt(process.env.OUTBOX_INTERVAL_MS || '1000', 10));
})().catch((e) => {
  console.error('Fatal:', e);
  process.exit(1);
});
